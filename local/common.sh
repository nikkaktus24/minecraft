mc_version="1.20.1"
forge_default="47.4.20"
installer_name="forge-1.20.1-47.4.20-installer.jar"

load_dotenv() {
  local file="$1"
  [[ -f "$file" ]] || return 0
  local line key value
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%%$'\r'}"
    [[ -z "$line" || "$line" == \#* ]] && continue
    [[ "$line" != *=* ]] && continue
    key="${line%%=*}"
    value="${line#*=}"
    case "$key" in
      *[!A-Za-z0-9_]* | "") continue ;;
    esac
        if [[ -z "${!key+x}" ]]; then
      printf -v "$key" '%s' "$value"
      export "$key"
    fi
  done < "$file"
}

load_local_env() {
  # Existing environment wins, then .env, then .env.example defaults.
  load_dotenv "$root/.env"
  load_dotenv "$root/.env.example"
  MEMORY="${MEMORY:-5G}"
  SERVER_PORT="${SERVER_PORT:-25565}"
  FORGE_VERSION="${FORGE_VERSION:-$forge_default}"
  MOTD="${MOTD:-IC2 1.20.1 — /login after join}"
  DIFFICULTY="${DIFFICULTY:-normal}"
  MODE="${MODE:-survival}"
  ONLINE_MODE="${ONLINE_MODE:-false}"
  ENFORCE_SECURE_PROFILE="${ENFORCE_SECURE_PROFILE:-false}"
  MAX_PLAYERS="${MAX_PLAYERS:-3}"
  VIEW_DISTANCE="${VIEW_DISTANCE:-10}"
  SIMULATION_DISTANCE="${SIMULATION_DISTANCE:-10}"
  LEVEL="${LEVEL:-world}"
  MAX_TICK_TIME="${MAX_TICK_TIME:--1}"
  USE_AIKAR_FLAGS="${USE_AIKAR_FLAGS:-true}"
  SERVER_PASSWORD="${SERVER_PASSWORD:-ic2play}"
  # Local always accepts the Mojang EULA (not ONLINE_MODE). Distinct from
  # compose's Portainer default, which this branch does not change.
  EULA=TRUE
  export MEMORY SERVER_PORT FORGE_VERSION MOTD DIFFICULTY MODE ONLINE_MODE \
    ENFORCE_SECURE_PROFILE MAX_PLAYERS VIEW_DISTANCE SIMULATION_DISTANCE \
    LEVEL MAX_TICK_TIME USE_AIKAR_FLAGS SERVER_PASSWORD EULA
}

java_major() {
  "$1" -version 2>&1 | python3 -c 'import sys,re; m=re.search(r"version \"(\d+)", sys.stdin.read()); print(m.group(1) if m else 0)'
}

find_java() {
  local candidate major
  if [[ -n "${JAVA_BIN:-}" && -x "$JAVA_BIN" ]]; then
    printf '%s\n' "$JAVA_BIN"
    return 0
  fi
  if [[ -n "${JAVA_HOME:-}" && -x "${JAVA_HOME}/bin/java" ]]; then
    printf '%s\n' "${JAVA_HOME}/bin/java"
    return 0
  fi
  for candidate in \
    /usr/lib/jvm/java-17-openjdk-amd64/bin/java \
    /usr/lib/jvm/java-17-openjdk/bin/java \
    /usr/lib/jvm/temurin-17-jdk-amd64/bin/java \
    /usr/lib/jvm/temurin-17/bin/java; do
    if [[ -x "$candidate" ]]; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done
  if command -v java >/dev/null 2>&1; then
    command -v java
    return 0
  fi
  return 1
}

require_java() {
  local bin major
  if ! bin="$(find_java)"; then
    echo "Java 17 is required (Minecraft 1.20.1 / Forge ${FORGE_VERSION})." >&2
    echo "Debian/Ubuntu:  sudo apt-get install -y openjdk-17-jre-headless" >&2
    echo "Then:  export JAVA_HOME=/usr/lib/jvm/java-17-openjdk-amd64" >&2
    echo "Or set JAVA_BIN to a Java 17 java executable." >&2
    return 1
  fi
  major="$(java_major "$bin")"
  if [[ "$major" -lt 17 ]]; then
    echo "Found $bin (Java $major). Need Java 17+ (17 preferred) for Forge 1.20.1." >&2
    return 1
  fi
  if [[ "$major" -ne 17 ]]; then
    echo "warning: $bin is Java $major; this pack is pinned to Java 17. Set JAVA_BIN to a 17 JRE if the server fails to start." >&2
  fi
  JAVA_BIN="$bin"
  export JAVA_BIN
  echo "Using $JAVA_BIN (Java $major)"
}

pid_is_running() {
  local pid="$1"
  [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null
}

read_pid() {
  [[ -f "$pid_file" ]] || return 1
  tr -d ' \t\r\n' < "$pid_file"
}

