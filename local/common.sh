write_jvm_args() {
  local out="$server_dir/user_jvm_args.txt"
  {
    echo "# Generated by local/install.sh / local/start.sh. Heap from MEMORY ($MEMORY)."
    echo "-Xms${MEMORY}"
    echo "-Xmx${MEMORY}"
    if [[ "${USE_AIKAR_FLAGS,,}" == "true" ]]; then
      echo "-XX:+UseG1GC"
      echo "-XX:+ParallelRefProcEnabled"
      echo "-XX:MaxGCPauseMillis=200"
      echo "-XX:+UnlockExperimentalVMOptions"
      echo "-XX:+DisableExplicitGC"
      echo "-XX:+AlwaysPreTouch"
      echo "-XX:G1NewSizePercent=30"
      echo "-XX:G1MaxNewSizePercent=40"
      echo "-XX:G1HeapRegionSize=8M"
      echo "-XX:G1ReservePercent=20"
      echo "-XX:G1HeapWastePercent=5"
      echo "-XX:G1MixedGCCountTarget=4"
      echo "-XX:InitiatingHeapOccupancyPercent=15"
      echo "-XX:G1MixedGCLiveThresholdPercent=90"
      echo "-XX:G1RSetUpdatingPauseTimePercent=5"
      echo "-XX:SurvivorRatio=32"
      echo "-XX:+PerfDisableSharedMem"
      echo "-XX:MaxTenuringThreshold=1"
      echo "-Dusing.aikar.flags=https://mcflags.emc.gs"
      echo "-Daikar.flags=true"
    fi
  } > "$out"
}

upsert_server_properties() {
  python3 - "$server_dir/server.properties" <<'PY'
import sys
from pathlib import Path

path = Path(sys.argv[1])
updates = {
    "online-mode": __import__("os").environ.get("ONLINE_MODE", "false"),
    "enforce-secure-profile": __import__("os").environ.get("ENFORCE_SECURE_PROFILE", "false"),
    "max-players": __import__("os").environ.get("MAX_PLAYERS", "3"),
    "motd": __import__("os").environ.get("MOTD", "IC2 1.20.1 — /login after join"),
    "difficulty": __import__("os").environ.get("DIFFICULTY", "normal"),
    "gamemode": __import__("os").environ.get("MODE", "survival"),
    "view-distance": __import__("os").environ.get("VIEW_DISTANCE", "10"),
    "simulation-distance": __import__("os").environ.get("SIMULATION_DISTANCE", "10"),
    "level-name": __import__("os").environ.get("LEVEL", "world"),
    "max-tick-time": __import__("os").environ.get("MAX_TICK_TIME", "-1"),
    "server-port": __import__("os").environ.get("SERVER_PORT", "25565"),
    "enable-rcon": "false",
    "sync-chunk-writes": "true",
}
lines = path.read_text().splitlines() if path.exists() else []
seen = set()
out = []
for line in lines:
    raw = line.strip()
    if not raw or raw.startswith("#") or "=" not in line:
        out.append(line)
        continue
    key = line.split("=", 1)[0]
    if key in updates:
        out.append(f"{key}={updates[key]}")
        seen.add(key)
    else:
        out.append(line)
for key, value in updates.items():
    if key not in seen:
        out.append(f"{key}={value}")
path.write_text("\n".join(out) + "\n")
PY
}
